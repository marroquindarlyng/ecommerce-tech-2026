-- Crea usuarios de plataforma y solicitudes de producto para aprobacion.

CREATE TABLE ADMIN.USUARIO_PORTAL (
    ID_USUARIO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ID_CLIENTE NUMBER NULL,
    NOMBRE VARCHAR2(160) NOT NULL,
    CORREO VARCHAR2(180) NOT NULL,
    PASSWORD_HASH VARCHAR2(256) NOT NULL,
    PASSWORD_SALT VARCHAR2(64) NOT NULL,
    ROL VARCHAR2(20) NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
    NIT VARCHAR2(32) DEFAULT 'CF',
    TELEFONO VARCHAR2(40),
    DIRECCION_ENVIO VARCHAR2(500),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    VALIDATED_AT TIMESTAMP NULL,
    CONSTRAINT UK_USUARIO_PORTAL_CORREO UNIQUE (CORREO),
    CONSTRAINT CK_USUARIO_PORTAL_ROL CHECK (ROL IN ('admin', 'vendedor', 'cliente')),
    CONSTRAINT CK_USUARIO_PORTAL_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'APROBADO', 'DENEGADO')),
    CONSTRAINT FK_USUARIO_PORTAL_CLIENTE FOREIGN KEY (ID_CLIENTE)
        REFERENCES ADMIN.CLIENTE (ID_CLIENTE)
);

CREATE TABLE ADMIN.SOLICITUD_PRODUCTO (
    ID_SOLICITUD NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ID_PRODUCTO NUMBER NULL,
    ID_USUARIO_SOLICITA NUMBER NOT NULL,
    ID_USUARIO_VALIDA NUMBER NULL,
    ID_CATEGORIA NUMBER NOT NULL,
    CODIGO_SKU VARCHAR2(80) NOT NULL,
    NOMBRE VARCHAR2(200) NOT NULL,
    PRECIO_UNITARIO NUMBER(12, 2) NOT NULL,
    STOCK_ACTUAL NUMBER DEFAULT 0 NOT NULL,
    FICHA_TECNICA CLOB,
    URL_GALERIA VARCHAR2(500),
    ESTADO VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
    OBSERVACIONES VARCHAR2(500),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    VALIDATED_AT TIMESTAMP NULL,
    CONSTRAINT CK_SOL_PRODUCTO_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'APROBADO', 'DENEGADO')),
    CONSTRAINT FK_SOL_PRODUCTO_SOLICITA FOREIGN KEY (ID_USUARIO_SOLICITA)
        REFERENCES ADMIN.USUARIO_PORTAL (ID_USUARIO),
    CONSTRAINT FK_SOL_PRODUCTO_VALIDA FOREIGN KEY (ID_USUARIO_VALIDA)
        REFERENCES ADMIN.USUARIO_PORTAL (ID_USUARIO),
    CONSTRAINT FK_SOL_PRODUCTO_CATEGORIA FOREIGN KEY (ID_CATEGORIA)
        REFERENCES ADMIN.CATEGORIA (ID_CATEGORIA),
    CONSTRAINT FK_SOL_PRODUCTO_PRODUCTO FOREIGN KEY (ID_PRODUCTO)
        REFERENCES ADMIN.PRODUCTO (ID_PRODUCTO)
);

